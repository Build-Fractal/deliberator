def init_project(
    project_root: Path,
    *,
    runtimes: list[str] | None = None,
    default_provider: str = "claude-code",
    default_model: str = "sonnet",
    force: bool = False,
) -> dict[str, Path]:
    """Initialize a ``.deliberator/`` directory and runtime configs.

    Creates the directory structure, settings files, and runtime-specific
    permission grants.  Idempotent — re-running updates settings without
    destroying existing output.

    Args:
        project_root: The project directory.
        runtimes: List of runtime names to configure (e.g.,
            ``["claude-code", "opencode"]``).  Defaults to
            ``["claude-code"]`` if not specified.
        default_provider: Default execution provider name.
        default_model: Default model identifier.
        force: If True, overwrite existing settings files.

    Returns:
        Dict of created/updated file paths keyed by description.
    """
    if runtimes is None:
        runtimes = ["claude-code"]

    deliberator_dir = project_root / DELIBERATOR_DIR
    output_dir = deliberator_dir / "output"

    # Create .deliberator/ and output/
    deliberator_dir.mkdir(exist_ok=True)
    output_dir.mkdir(exist_ok=True)

    created: dict[str, Path] = {}

    # Write .deliberator/settings.yml (the cascade reader expects YAML; spec 057
    # SC-001 — fix writer/reader format mismatch that was shipping orphan
    # settings.json files).
    settings_path = deliberator_dir / SETTINGS_FILE
    legacy_settings_path = deliberator_dir / LEGACY_SETTINGS_FILE
    if not settings_path.exists() or force:
        settings: dict[str, Any] = {
            **DEFAULT_SETTINGS,
            "default_provider": default_provider,
            "default_model": default_model,
            "runtimes": runtimes,
        }

        # Best-effort migration from a legacy orphan settings.json. We only
        # *read* from it — the legacy file is left in place so the user can
        # confirm and remove it themselves (no destructive ops without
        # explicit confirmation).
        if legacy_settings_path.is_file():
            try:
                legacy_data = json.loads(
                    legacy_settings_path.read_text(encoding="utf-8")
                )
                if isinstance(legacy_data, dict):
                    # Preserve user-added custom keys from the legacy file but
                    # let fresh init args win for shared keys.
                    settings = {**legacy_data, **settings}
                    created["legacy_migrated"] = legacy_settings_path
                else:
                    logger.warning(
                        "Legacy %s is not a JSON object — skipping migration",
                        legacy_settings_path,
                    )
            except (json.JSONDecodeError, OSError) as exc:
                logger.warning(
                    "Could not read legacy settings at %s: %s — writing fresh defaults",
                    legacy_settings_path,
                    exc,
                )

        settings_path.write_text(
            yaml.safe_dump(settings, default_flow_style=False, sort_keys=False),
            encoding="utf-8",
        )
        created["settings"] = settings_path

    # Write .deliberator/.gitignore
    gitignore_path = deliberator_dir / GITIGNORE_FILE
    if not gitignore_path.exists() or force:
        gitignore_path.write_text(GITIGNORE_CONTENT, encoding="utf-8")
        created["gitignore"] = gitignore_path

    # Generate runtime-specific configs
    for runtime in runtimes:
        # Special case: claude-code uses merge semantics to preserve
        # existing .claude/settings.json permissions and hooks.
        if runtime == "claude-code":
            result = _merge_claude_settings(project_root, force=force)
            if result is not None:
                created["runtime:claude-code"] = result
            continue

        config_fn = RUNTIME_CONFIGS.get(runtime)
        if config_fn is None:
            continue

        dir_name, filename, content = config_fn()

        if dir_name:
            config_dir = project_root / dir_name
            config_dir.mkdir(exist_ok=True)
            config_path = config_dir / filename
        else:
            # Files that go in project root (e.g., .aider.conf.yml)
            config_path = project_root / filename

        if not config_path.exists() or force:
            config_path.write_text(content, encoding="utf-8")
            created[f"runtime:{runtime}"] = config_path

    return created


def read_settings(project_root: Path) -> dict[str, Any]:
    """Read ``.deliberator/settings.yml`` from the project root.

    Returns default settings if the file doesn't exist or is malformed.

    Note: this is a thin loader for ``init``-related helpers. The full
    settings cascade lives in :mod:`engine.settings` (``load_settings``).
    """
    settings_path = project_root / DELIBERATOR_DIR / SETTINGS_FILE
    if not settings_path.exists():
        return dict(DEFAULT_SETTINGS)
    try:
        data = yaml.safe_load(settings_path.read_text(encoding="utf-8"))
    except (yaml.YAMLError, OSError):
        return dict(DEFAULT_SETTINGS)
    if not isinstance(data, dict):
        return dict(DEFAULT_SETTINGS)
    return data


def find_deliberator_dir(start: Path) -> Path | None:
    """Walk up from *start* to find a ``.deliberator/`` directory.

    Returns the ``.deliberator/`` path if found, or ``None``.
    """
    current = start.resolve()
    while current != current.parent:
        candidate = current / DELIBERATOR_DIR
        if candidate.is_dir():
            return candidate
        current = current.parent
    return None
