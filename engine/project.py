#: Maps provider names to their config generator functions.
RUNTIME_CONFIGS: dict[str, Any] = {
    "claude-code": _claude_config,
    "opencode": _opencode_config,
    "copilot": _copilot_config,
    "gemini": _gemini_config,
    "codex": _codex_config,
    "aider": _aider_config,
}

#: All runtime names that have config generators.
AVAILABLE_RUNTIMES = sorted(RUNTIME_CONFIGS.keys())


